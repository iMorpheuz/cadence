export const EXERCISE_MAP = new Map(EXERCISES.map((ex) => [ex.id, ex]));

export function unitWord(unit: Unit, n: number) {
  if (unit === "side") return n === 1 ? "each side" : "each side";
  if (unit === "sec") return "sec";
  if (unit === "cycles") return n === 1 ? "cycle" : "cycles";
  return n === 1 ? "rep" : "reps";
}

export function formatTarget(reps: number, sets: number, unit: Unit) {
  const body = `${reps} ${unitWord(unit, reps)}`;
  if (sets <= 1) return body;
  return `${sets} × ${body}`;
}

export function jumpOffsets(mode: "build" | "ink") {
  const offsets: Record<string, number> = {};
  for (const ex of EXERCISES) offsets[ex.id] = mode === "ink" ? inkOffset(ex) : 0;
  return offsets;
}
